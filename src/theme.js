export const DEFAULT_THEME_ID = "yellow";

export function getTheme(themeId) {
  return themes[themeId] || themes[DEFAULT_THEME_ID];
}

export function applyTheme(themeId) {
  const current = getTheme(themeId);
  const root = document.documentElement;

  root.style.setProperty("--theme-primary", current.hex);
  root.style.setProperty("--theme-bg", current.bgHex);
  root.style.setProperty("--theme-card-bg", current.cardHex);
  root.style.setProperty("--theme-contrast", current.contrastHex);
  root.style.setProperty("--theme-accent", current.accentHex);
  root.style.setProperty("--theme-nav-bg", current.navBg);

  try {
    localStorage.setItem("app_theme", current.id);
  } catch (e) {
    console.error("Failed to store theme preference in localStorage", e);
  }

  return current;
}

